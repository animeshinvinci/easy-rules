package org.jeasy.rules.postgresql;

import org.jeasy.rules.support.RuleDefinition;

/**
 * Extended rule definition that includes database-specific metadata.
 * This class extends the base RuleDefinition to include the database rule ID
 * which is needed for loading related data like actions and composing rules.
 *
 * @author Easy Rules Team
 */
public class ExtendedRuleDefinition extends RuleDefinition {

    private Long ruleId;

    public Long getRuleId() {
        return ruleId;
    }

    public void setRuleId(Long ruleId) {
        this.ruleId = ruleId;
    }
}